#[test]
fn operator_fingerprints() {
    // Recorded from the string-operator AST at e878c63c, before migration.
    for (formula, expected) in [
        ("=A1+1", 16884703858563636240),
        ("=-A1", 16298865845475352149),
        ("=+A1", 288547078900481411),
        ("=A1%", 3182091174043072205),
        ("=A1#", 5618516481177753083),
        ("=@A1", 17651873590124308780),
        ("=A1:B2", 6275940170391122388),
        ("=A1,B2", 9271896173410629021),
        ("=A1 B2", 3823525462125985881),
        ("=A1-B1*C1/D1^E1&F1", 14963481061432017308),
        ("=A1=B1", 12479887148427829253),
        ("=A1<>B1", 1683982932711411698),
        ("=A1<B1", 4919592308467201526),
        ("=A1>B1", 366149900897896396),
        ("=A1<=B1", 18082865157521360231),
        ("=A1>=B1", 1165767857619087609),
    ] {
        let ast = formualizer_parse::parse(formula).unwrap();
        assert_eq!(ast.fingerprint(), expected, "{formula}");
    }
}
